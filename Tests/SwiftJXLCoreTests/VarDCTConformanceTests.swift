import Foundation
import Testing
@testable import SwiftJXLCore

struct VarDCTConformanceTests {
    private func budget() throws -> ScalarOperationBudget {
        try ScalarOperationBudget(retainedBytes: 0, maximumWorkspaceBytes: 64 * 1024 * 1024,
            maximumMemoryBytes: 64 * 1024 * 1024, maximumDecodedBytes: 64 * 1024 * 1024,
            maximumCompressedBytes: 4 * 1024 * 1024, deadline: .now.advanced(by: .seconds(30)))
    }
    private func fixture(_ name: String, extension suffix: String) throws -> Data {
        let url = try #require(Bundle.module.url(forResource: name, withExtension: suffix,
            subdirectory: "VarDCT/Conformance"))
        return try Data(contentsOf: url)
    }

    // These limits and Float32 linear-grey samples are supplied by the pinned
    // official conformance corpus, not generated by the implementation under
    // test. This is a scoped reconstruction check, not whole-codec conformance.
    @Test(arguments: ["grayscale", "grayscale_5"])
    func prescribedLinearGreyReference(_ name: String) throws {
        let source = try fixture(name, extension: "jxl")
        let envelope = try VarDCTFrameEnvelope.read(source, budget: budget())
        #expect(envelope.width == 200 && envelope.height == 200)
        #expect(envelope.metadata.colorEncoding.useICC)
        #expect(try envelope.iccProfile == fixture("original", extension: "icc"))
        let planes = try VarDCTReconstruction.xyb(VarDCTCoefficients.read(envelope))
        let expected = try fixture("reference", extension: "npy")
        // The pinned NPY v1 fixture's trusted header declares <f4, C-order,
        // (1,200,200,1). Preserve its complete original file and hash.
        #expect(expected.prefix(8) == Data([0x93,78,85,77,80,89,1,0]))
        let start = 10 + Int(expected[8]) + Int(expected[9]) * 256
        #expect(start == 80 && expected.count == start + 40000 * 4)
        var peak = 0.0, squared = 0.0
        for i in 0..<40000 {
            let rgb = try DefaultOpsin.inverse((X: Double(planes[0][i]),
                Y: Double(planes[1][i]), B: Double(planes[2][i])))
            let bits = expected.withUnsafeBytes { $0.loadUnaligned(fromByteOffset: start + i * 4, as: UInt32.self) }
            let reference = Double(Float(bitPattern: UInt32(littleEndian: bits)))
            let error = abs(rgb.R - reference)
            peak = max(peak, error); squared += error * error
        }
        #expect(peak <= 0.004)
        #expect(sqrt(squared / 40000) <= 0.0001)
    }

    @Test func ICCLimitsAndInterpretationRemainExplicit() throws {
        let source = try fixture("grayscale", extension: "jxl")
        for maximum in [0, 128, 911] {
            #expect(throws: (any Error).self) {
                try VarDCTFrameEnvelope.read(source, budget: budget(), maximumICCBytes: maximum)
            }
            #expect(throws: (any Error).self) {
                try VarDCTFrameEnvelope.read(source, budget: budget(), maximumMetadataBytes: maximum)
            }
        }
        let envelope = try VarDCTFrameEnvelope.read(source, budget: budget(), maximumICCBytes: 912,
            maximumMetadataBytes: 912)
        #expect(envelope.iccProfile?.count == 912)
        let layout = try ModularChannelLayout(width: 200, height: 200, offset: 0,
            rowBytes: 200, pixelStride: 1, storageBits: 8, littleEndian: true)
        var output = [UInt8](repeating: 0xA5, count: 40000)
        #expect(throws: (any Error).self) {
            try output.withUnsafeMutableBytes { try VarDCTPixelDecoder.decode(envelope, into: $0, layouts: [layout]) }
        }
        #expect(output.allSatisfy { $0 == 0xA5 })
    }
}
