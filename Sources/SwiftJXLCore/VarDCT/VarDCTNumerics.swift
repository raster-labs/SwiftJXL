    /// Computes the IEEE-754 single-precision ARMv8-A `FRECPE` reciprocal estimate of `Float(q)`.
    package static func reciprocalEstimate(_ q: Int32) -> Float {
        if q == 0 {
            return Float(bitPattern: 0x7F80_0000)
        }
        let f = Float(q)
        let bits = f.bitPattern
        let sign = bits & 0x8000_0000
        let exp = Int((bits >> 23) & 0xFF)
        if exp == 0 {
            return Float(bitPattern: sign | 0x7F80_0000)
        }
        if exp == 0xFF {
            return (bits & 0x007F_FFFF) == 0 ? Float(bitPattern: sign) : f
        }
        let idx = Int((bits >> 15) & 0xFF)
        let d = 256 + idx
        let est = ((524_288 / (2 * d + 1)) + 1) / 2 - 256
        let outExp = 253 - exp
        if outExp <= 0 {
            return Float(bitPattern: sign)
        }
        if outExp >= 0xFF {
            return Float(bitPattern: sign | 0x7F80_0000)
        }
        let outBits = sign | (UInt32(outExp) << 23) | (UInt32(est & 0xFF) << 15)
        return Float(bitPattern: outBits)
    }

    /// Converts a bounded `[0, 1]` sRGB sample to an `n`-bit integer under the ARM integer profile.
    package static func integer(_ encoded: Double, bits: Int, x: Int, y: Int, channel: Int) -> Int32 {
        let maximum = Double((1 << bits) - 1)
        let clamped = min(1.0, max(0.0, encoded))
        let scaled = clamped * maximum
        if bits == 8 {
            let dx = (x &+ channel &* 9) & 31
            let dy = (y &+ channel &* 19) & 31
            let dither = Double(dither32x32[(dy << 5) | dx]) / 256.0
            return Int32(min(maximum, max(0.0, Foundation.floor(scaled + dither))))
        }
        return Int32(scaled.rounded())
    }
